/**
 * Benchmark data integrity — the /benchmark page must show real measured
 * numbers, never placeholders: every entry positive, plausible, and tied
 * to an existing sample file.
 */
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import data from "./data.json";

describe("benchmark data.json", () => {
  it("was generated by the script (has the engine + runs metadata)", () => {
    expect(data.engine).toBe("anydoc-wasm 0.1.7");
    expect(data.runsPerSample).toBeGreaterThanOrEqual(10);
    expect(data.generated).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });

  it("every sample has real, positive timings and a matching file", () => {
    const samples = data.samples as Record<string, { file: string; medianMs: number; minMs: number; chars: number }>;
    expect(Object.keys(samples).length).toBeGreaterThanOrEqual(5);
    for (const [label, s] of Object.entries(samples)) {
      expect(s.medianMs, label).toBeGreaterThan(0);
      expect(s.minMs, label).toBeGreaterThan(0);
      expect(s.minMs, label).toBeLessThanOrEqual(s.medianMs);
      expect(s.chars, label).toBeGreaterThanOrEqual(0);
      expect(existsSync(path.join(process.cwd(), "samples", s.file)), s.file).toBe(true);
    }
  });
});
